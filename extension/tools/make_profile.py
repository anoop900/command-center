#!/usr/bin/env python3
"""Build profile.json for the extension from Candidate_Profile.md section 9.

Usage: python3 make_profile.py Candidate_Profile.md [out=profile.json]
Fails loudly if a field cannot be found, so a profile edit never silently blanks a form answer.
profile.json holds the street address and phone: it is gitignored and must stay local.
"""
import json, re, sys

src = open(sys.argv[1], encoding="utf-8").read()
out = sys.argv[2] if len(sys.argv) > 2 else "profile.json"
m = re.search(r"## 9\..*?(?=\n## |\Z)", src, re.S)
if not m:
    sys.exit("section 9 not found")
s9 = m.group(0)


# Former employers from the section 2 table: first column, "Name (ABBR), City" -> ["Name", "ABBR"].
employers = []
t2 = re.search(r"## 2\..*?(?=\n## )", src, re.S)
for row in (t2.group(0).splitlines() if t2 else []):
    if not row.startswith("|") or row.startswith("|---") or "Employer" in row:
        continue
    cell = row.split("|")[1].strip()
    parts = re.split(r",\s*(?=[A-Z])", cell)
    # "Employer, City": a last part that is one word (a city or "Remote") is a location, not an employer.
    # "Employer A, Employer B" (two employers on one row) keeps both.
    if len(parts) > 1 and re.fullmatch(r"[A-Z][a-z]+", parts[-1]):
        parts = parts[:-1]
    for part in parts:
        ab = re.search(r"\(([A-Z]{2,})\)", part)
        name = re.sub(r"\s*\([^)]*\)", "", part).strip()
        employers += [x for x in (name, ab and ab.group(1)) if x]
if not employers:
    sys.exit("section 2 employer table not found")
rehire = {m.group(1): m.group(2) for m in re.finditer(r"(\w+) rehire eligibility:\s*(\w+)", src)}


PROVINCES = {"ON": "Ontario", "BC": "British Columbia", "AB": "Alberta", "QC": "Quebec", "MB": "Manitoba", "SK": "Saskatchewan",
             "NS": "Nova Scotia", "NB": "New Brunswick", "NL": "Newfoundland and Labrador", "PE": "Prince Edward Island"}


def grab(pattern, label):
    g = re.search(pattern, s9)
    if not g:
        sys.exit(f"missing in section 9: {label}")
    return g.group(1).strip().rstrip(".")


name = grab(r"Legal name:\s*([^.]+)\.", "legal name")
first, last = name.split(" ", 1)
city_line = grab(r"City:\s*([^.]+)\.", "city")  # "City, PROV, Country"
city, prov, country = [x.strip() for x in city_line.split(",")]
profile = {
    "_source": "Candidate_Profile.md section 9 (generated by tools/make_profile.py)",
    "firstName": first,
    "lastName": last,
    "email": grab(r"Email:\s*(\S+?)\.?\s", "email"),
    "phone": grab(r"Phone:\s*([\d-]+)", "phone"),
    "address1": grab(r"Street address:\s*([^,]+),", "street address"),
    "city": city,
    "province": PROVINCES.get(prov, prov),
    "provinceCode": prov,
    "postalCode": grab(r"Postal code:\s*([A-Z]\d[A-Z] ?\d[A-Z]\d)", "postal code"),
    "country": country,
    "linkedin": "https://www." + grab(r"LinkedIn:\s*(\S+?)\.\s", "linkedin"),
    "website": "https://" + grab(r"Website:\s*([a-z0-9.-]+\.[a-z]+)", "website"),
    # Yes/no answers, each traced to a section 9 sentence.
    "authorizedHome": grab(r"Legally entitled to work in [A-Za-z ]+:\s*(Yes|No)", "work authorization (home country)"),
    "sponsorshipHome": grab(r"Requires sponsorship for [A-Za-z ]+:\s*(Yes|No)", "sponsorship (home country)"),
    "phoneCountryCode": "1" if country in ("Canada", "United States") else "",
    "relocate": "Yes" if "Open to relocation: Yes" in s9 else sys.exit("relocation"),
    "startDate": grab(r"(?:Notice period / )?earliest start date:\s*([^.(]+)", "earliest start date"),
    "clearance": grab(r"Security clearance:\s*([^\n]+?)\.?\n", "clearance"),
    "education": grab(r"Highest education:\s*([^.]+)\.", "education"),
    "englishFluent": "Yes",
    "frenchFluent": "No" if "fluent in English only" in s9 else sys.exit("languages"),
    # v0.3 (Oct 9): citizenship, US, bachelor's, school, previously applied/worked.
    "citizenship": grab(r"Citizenship:\s*([A-Za-z ]+)\.", "citizenship"),
    "usAuthText": grab(r'US work authorization free text:\s*"([^"]+)"', "US work authorization text"),
    "usAuthorizedNow": grab(r'"Currently authorized to work in the US":\s*(Yes|No)', "US authorized now"),
    "bachelorYesNo": grab(r"Bachelor's yes/no questions[^:]*\):\s*(Yes|No)", "bachelor yes/no"),
    "school": grab(r'School pickers: choose "([^"]+)"', "school"),
    "schoolAlt": grab(r'School pickers: choose "[^"]+" or "([^"]+)"', "school alt"),
    "schoolOtherText": grab(r'else "Other" and type "([^"]+)"', "school other text"),
    "fieldOfStudy": grab(r"Field of study:\s*([^.]+)\.", "field of study"),
    "eduStart": grab(r"Years:\s*(\d{4})", "education start"),
    "eduEnd": grab(r"Years:\s*\d{4} to (\d{4})", "education end"),
    "previouslyApplied": grab(r"Previously applied here:\s*(Yes|No)", "previously applied"),
    "formerEmployers": employers,
    "rehire": rehire,
}
json.dump(profile, open(out, "w", encoding="utf-8"), indent=2)
print(f"wrote {out}: {len(profile)} fields")
