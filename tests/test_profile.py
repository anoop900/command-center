"""Wizard step 3 (form path): only confirmed facts are written, hand-written files are never overwritten,
and hostile text cannot change the structure of Candidate_Profile.md."""
import http.client
import json
import tempfile
import threading
import unittest
from pathlib import Path

from cc import profile, web


def form(**kw):
    base = {
        "fields": {"firstName": {"value": "Jordan", "ok": True}, "lastName": {"value": "Example", "ok": True},
                   "email": {"value": "jordan@example.com", "ok": True}, "phone": {"value": "555-010-0199", "ok": False},
                   "authorizedHome": {"value": "Yes", "ok": True}},
        "jobs": [{"employer": "Northwind", "title": "Director", "dates": "2021 - now", "facts": ["Led 22 people."], "ok": True},
                 {"employer": "Contoso", "title": "Manager", "dates": "2017 - 2021", "facts": ["Ran 9 people."], "ok": False}],
        "skills": {"value": "AWS, Terraform", "ok": True},
    }
    base.update(kw)
    return base


class ProfileFiles(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.d = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def test_only_confirmed_facts_are_written(self):
        r = profile.save(self.d, form())
        self.assertEqual(r["unconfirmed"], 2)  # the phone and the Contoso job
        pj = json.loads((self.d / "profile.json").read_text(encoding="utf-8"))
        self.assertEqual(pj["firstName"], "Jordan")
        self.assertNotIn("phone", pj)
        md = (self.d / "Candidate_Profile.md").read_text(encoding="utf-8")
        self.assertIn("Northwind", md)
        self.assertIn("Led 22 people", md)
        self.assertNotIn("Contoso", md)
        self.assertNotIn("555-010-0199", md)
        self.assertIn("AWS, Terraform", md)

    def test_blank_form_writes_nothing_invented(self):
        profile.save(self.d, profile.empty())
        self.assertEqual(list(json.loads((self.d / "profile.json").read_text(encoding="utf-8"))), ["_source"])
        md = (self.d / "Candidate_Profile.md").read_text(encoding="utf-8")
        self.assertNotIn("Canada", md)
        self.assertNotIn("Yes", md)

    def test_rerun_is_idempotent_and_load_round_trips(self):
        profile.save(self.d, form())
        first = (self.d / "Candidate_Profile.md").read_text(encoding="utf-8")
        profile.save(self.d, profile.load(self.d))
        self.assertEqual((self.d / "Candidate_Profile.md").read_text(encoding="utf-8"), first)

    def test_imported_v3_profile_is_replaced_only_after_a_copy_is_kept(self):
        old = '{"_source": "Candidate_Profile.md section 9 (generated by tools/make_profile.py)", "firstName": "Old"}'
        (self.d / "profile.json").write_text(old, encoding="utf-8")
        profile.save(self.d, form())
        self.assertEqual((self.d / "profile.previous.json").read_text(encoding="utf-8"), old)
        self.assertIn(profile.MARK, (self.d / "profile.json").read_text(encoding="utf-8"))
        profile.save(self.d, form())  # second save: the wizard's own file, the backup is not touched again
        self.assertEqual((self.d / "profile.previous.json").read_text(encoding="utf-8"), old)

    def test_every_extension_field_has_a_box_and_list_fields_round_trip(self):
        import json as _json
        ex = _json.loads((Path(__file__).resolve().parent.parent / "extension" / "profile.example.json").read_text(encoding="utf-8"))
        self.assertEqual(sorted(k for k in ex if not k.startswith("_") and k not in profile.KINDS), [])
        raw = form()
        raw["fields"]["formerEmployers"] = {"value": "Acme Ltd\nGlobex Corp\n\n", "ok": True}
        raw["fields"]["rehire"] = {"value": ["Acme Ltd: Eligible"], "ok": True}
        raw["fields"]["usAuthorizedNow"] = {"value": "No", "ok": True}
        profile.save(self.d, raw)
        out = _json.loads((self.d / "profile.json").read_text(encoding="utf-8"))
        self.assertEqual(out["formerEmployers"], ["Acme Ltd", "Globex Corp"])
        self.assertEqual(out["rehire"], {"Acme Ltd": "Eligible"})
        self.assertEqual(out["usAuthorizedNow"], "No")
        self.assertEqual(profile.load(self.d)["fields"]["formerEmployers"]["value"], ["Acme Ltd", "Globex Corp"])
        for bad in ({"rehire": {"value": "no colon here", "ok": True}}, {"formerEmployers": {"value": ["x" * 200], "ok": True}},
                    {"usAuthorizedNow": {"value": "Maybe", "ok": True}}):
            with self.assertRaises(ValueError):
                profile.validate({**form(), "fields": bad})

    def test_hand_written_files_are_never_overwritten(self):
        (self.d / "Candidate_Profile.md").write_text("# My own profile\n", encoding="utf-8")
        with self.assertRaises(ValueError):
            profile.save(self.d, form())
        self.assertEqual((self.d / "Candidate_Profile.md").read_text(encoding="utf-8"), "# My own profile\n")
        self.assertFalse((self.d / "profile.json").exists())
        (self.d / "Candidate_Profile.md").unlink()
        (self.d / "profile.json").write_text('{"firstName": "Old"}', encoding="utf-8")
        with self.assertRaises(ValueError):
            profile.save(self.d, form())

    def test_markdown_structure_cannot_be_injected(self):
        hostile = form(jobs=[{"employer": "A | B", "title": "## 9. Fake", "dates": "x", "ok": True,
                              "facts": ["# Heading", "- nested", "| a | b |", "plain"]}])
        profile.save(self.d, hostile)
        md = (self.d / "Candidate_Profile.md").read_text(encoding="utf-8")
        heads = [l for l in md.splitlines() if l.startswith("## ")]
        self.assertEqual(len(heads), 7)  # sections 1-6 and 9, nothing added by the data
        self.assertNotIn("| a | b |", md)

    def test_bad_input_rejected(self):
        bad = [None, [], "x", {"fields": []}, {"fields": {"nope": {"value": "x", "ok": True}}},
               {"fields": {"email": {"value": "not-an-email", "ok": True}}},
               {"fields": {"relocate": {"value": "Maybe", "ok": True}}},
               {"fields": {"city": {"value": "a\nb", "ok": True}}},
               {"fields": {"city": {"value": "x" * 301, "ok": True}}},
               {"fields": {"city": {"value": 5, "ok": True}}},
               {"fields": {"city": {"value": "x", "ok": "yes"}}},
               {"jobs": [{"employer": "", "title": "x"}]},
               {"jobs": [{"employer": "a", "title": "b", "facts": "not a list"}]},
               {"jobs": [{"employer": "a", "title": "b"}] * 21},
               {"jobs": [{"employer": "a", "title": "b", "facts": ["x"] * 31}]},
               {"skills": "AWS"}, {"skills": {"value": "x" * 700}}]
        for b in bad:
            with self.assertRaises(ValueError, msg=repr(b)[:60]):
                profile.save(self.d, b)
        self.assertFalse((self.d / "profile.json").exists())

    def test_unconfirmed_blank_cannot_be_ticked(self):
        profile.save(self.d, {"fields": {"city": {"value": "", "ok": True}}})
        self.assertNotIn("city", json.loads((self.d / "profile.json").read_text(encoding="utf-8")))

    def test_damaged_draft_loads_as_blank(self):
        (self.d / profile.FORM_FILE).write_text("{not json", encoding="utf-8")
        self.assertEqual(profile.load(self.d), profile.empty())
        (self.d / profile.FORM_FILE).write_bytes(b"\xff\xfe\x00")
        self.assertEqual(profile.load(self.d), profile.empty())


class ContactLine(unittest.TestCase):
    def test_city_gets_abbreviated_province(self):
        f = {"city": "Springfield", "province": "Ontario", "phone": "1", "email": "e"}
        self.assertEqual(profile.contact_parts(f), ["Springfield, ON", "1", "e"])

    def test_unknown_province_kept_and_no_double(self):
        self.assertEqual(profile.contact_parts({"city": "Austin", "province": "Texas"})[0], "Austin, Texas")
        self.assertEqual(profile.contact_parts({"city": "Springfield, ON", "province": "Ontario"})[0], "Springfield, ON")
        self.assertEqual(profile.contact_parts({"city": "Springfield"}), ["Springfield"])
        self.assertEqual(profile.contact_parts({}), [])


class ProfileHttp(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.srv = web.make_server(self.tmp.name, 0)
        self.port = self.srv.server_address[1]
        threading.Thread(target=self.srv.serve_forever, daemon=True).start()

    def tearDown(self):
        self.srv.shutdown()
        self.srv.server_close()
        self.tmp.cleanup()

    def call(self, method, path, body=None, headers=None):
        for attempt in (1, 2):  # Windows loopback occasionally resets a fresh connection
            c = http.client.HTTPConnection("127.0.0.1", self.port, timeout=10)
            try:
                c.request(method, path, json.dumps(body if body is not None else {}), headers or {})
                r = c.getresponse()
                out = r.read()
                break
            except ConnectionError:
                c.close()
                if attempt == 2:
                    raise
        c.close()
        return r.status, json.loads(out)

    def test_round_trip_and_guards(self):
        st, j = self.call("GET", "/wizard/profile")
        self.assertEqual((st, j["state"]), (200, profile.empty()))
        self.assertEqual(self.call("POST", "/wizard/profile", form())[0], 200)
        self.assertEqual(self.call("GET", "/wizard/profile")[1]["state"]["fields"]["firstName"]["value"], "Jordan")
        self.assertEqual(self.call("POST", "/wizard/profile", {"fields": {"city": {"value": "a\nb"}}})[0], 400)
        self.assertEqual(self.call("POST", "/wizard/profile", form(), {"Origin": "http://evil.example"})[0], 403)
        self.assertEqual(self.call("GET", "/wizard/profile", headers={"Host": "evil.example"})[0], 403)
        self.assertEqual(self.call("POST", "/wizard/profile", form())[0], 200)  # our own file is replaced
        (Path(self.tmp.name) / "Candidate_Profile.md").write_text("hand written", encoding="utf-8")
        self.assertEqual(self.call("POST", "/wizard/profile", form())[0], 400)


if __name__ == "__main__":
    unittest.main()
